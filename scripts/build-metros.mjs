#!/usr/bin/env node
/**
 * Builds src/lib/metros.ts: every U.S. metro area of 250,000+ people, with
 * its counties, from the Census Bureau's free files (rerun when the Census
 * publishes new estimates or metro definitions):
 *
 *   curl -O https://www2.census.gov/programs-surveys/popest/datasets/2020-2024/metro/totals/cbsa-est2024-alldata.csv
 *   curl -O https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_cbsa_national.zip && unzip 2024_Gaz_cbsa_national.zip
 *   node scripts/build-metros.mjs cbsa-est2024-alldata.csv 2024_Gaz_cbsa_national.txt
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [popFile, gazFile] = process.argv.slice(2);
if (!popFile || !gazFile) { console.error('Usage: build-metros.mjs <cbsa-est-alldata.csv> <Gaz_cbsa_national.txt>'); process.exit(2); }
const MIN_POP = 250_000;

// State FIPS → postal code.
const FIPS = { '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE', '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV', '55': 'WI', '56': 'WY', '72': 'PR' };

// Connecticut replaced its 8 counties with 9 planning regions in 2022; the DOT census still uses the old
// counties, so each region maps to the old county (or counties) it mostly covers.
const CT_REGIONS = { '110': ['003', '013'], '120': ['001'], '130': ['007'], '140': ['009', '005'], '150': ['015'], '160': ['005'], '170': ['009'], '180': ['011', '015'], '190': ['001'] };

const csvLine = line => { const out = []; let f = '', q = false; for (const c of line) { if (q) { if (c === '"') q = false; else f += c; } else if (c === '"') q = true; else if (c === ',') { out.push(f); f = ''; } else f += c; } out.push(f); return out; };
const lines = readFileSync(popFile, 'latin1').split(/\r?\n/).filter(Boolean);
const head = csvLine(lines[0]), col = k => head.indexOf(k);
const popCol = head.filter(h => /^POPESTIMATE\d{4}$/.test(h)).sort().pop();
const metros = new Map();
for (const l of lines.slice(1)) {
  const r = csvLine(l), cbsa = r[col('CBSA')], lsad = r[col('LSAD')];
  if (lsad === 'Metropolitan Statistical Area') metros.set(cbsa, { cbsa, name: r[col('NAME')], pop: Number(r[col(popCol)]), counties: [] });
  else if (lsad === 'County or equivalent' && metros.has(cbsa)) {
    const st = FIPS[r[col('STCOU')].slice(0, 2)];
    const county = r[col('STCOU')].slice(2), list = metros.get(cbsa).counties;
    if (st === 'CT' && CT_REGIONS[county]) for (const c of CT_REGIONS[county]) { if (!list.includes(`CT-${c}`)) list.push(`CT-${c}`); }
    else if (st) list.push(`${st}-${county}`);
  }
}
const centers = new Map(readFileSync(gazFile, 'utf8').split(/\r?\n/).slice(1).filter(Boolean).map(l => { const p = l.split('\t').map(s => s.trim()); return [p[1], [Number(Number(p[8]).toFixed(3)), Number(Number(p[9]).toFixed(3))]]; }));

const list = [...metros.values()].filter(m => m.pop >= MIN_POP && m.counties.length).sort((a, b) => b.pop - a.pop).map(m => {
  // "Seattle-Tacoma-Bellevue, WA" → city "Seattle", label "Seattle–Tacoma–Bellevue, WA".
  // Census names, as people say them: "Urban Honolulu" → Honolulu, "Boise City" → Boise, "Louisville/Jefferson County" → Louisville,
  // "Nashville-Davidson--Murfreesboro--Franklin" → Nashville–Murfreesboro–Franklin, "Wilkes-Barre" keeps its hyphen.
  const [rawCities, states] = m.name.split(', ');
  const cities = rawCities.replace(/^Urban /, '').replace(/^Boise City/, 'Boise').replace(/\/Jefferson County/, '').replace('Nashville-Davidson--', 'Nashville--');
  const parts = (cities.includes('--') ? cities.split('--') : cities.replace('Winston-Salem', 'Winston\u2011Salem').split('-')).map(c => c.replace('\u2011', '-')); // Winston-Salem is one city.
  return { key: `msa-${m.cbsa}`, label: `${parts.join('–')}, ${states}`, city: parts[0], pop: m.pop, states: [...new Set(m.counties.map(c => c.slice(0, 2)))], counties: m.counties, center: centers.get(m.cbsa) || null };
});

const out = `/**
 * Every U.S. metro area of ${MIN_POP.toLocaleString()}+ people (${list.length}), largest first, with the
 * counties in each (state-county FIPS, e.g. "WA-033"), population (${popCol.slice(-4)}
 * Census estimate) and map center. Generated by scripts/build-metros.mjs
 * from the Census Bureau's free metro-area files; don't edit by hand.
 */
export type Metro = { key: string; label: string; city: string; pop: number; states: string[]; counties: string[]; center: [number, number] | null };

export const METROS: Metro[] = [
${list.map(m => `  ${JSON.stringify(m)},`).join('\n')}
];
`;
writeFileSync(new URL('../src/lib/metros.ts', import.meta.url), out);
console.log(`${list.length} metros (${popCol}); smallest: ${list.at(-1).label} ${list.at(-1).pop.toLocaleString()}; multi-state: ${list.filter(m => m.states.length > 1).length}; no center: ${list.filter(m => !m.center).length}`);
